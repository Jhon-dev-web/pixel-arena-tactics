// Regenerates src/game/skillFx.atlas.ts from the texture-atlas JSON files next to the PNG sheets in public/assets/vfx/ (run: node scripts/gen-skill-fx.mjs).
// The table is generated, not fetched at runtime: the JSON never ships to the player and the PNG size is read from the file header here.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve('public/assets/vfx');
const names = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, '')).sort();
const out = {};
for (const name of names) {
  const json = JSON.parse(fs.readFileSync(path.join(dir, `${name}.json`), 'utf8'));
  const png = fs.readFileSync(path.join(dir, `${name}.png`));
  const w = png.readUInt32BE(16);
  const h = png.readUInt32BE(20);
  out[name] = {
    url: `/assets/vfx/${name}.png`,
    w,
    h,
    frames: json.frames.map((f) => ({ x: f.frame.x, y: f.frame.y, w: f.frame.w, h: f.frame.h, px: Math.round(f.pivot.x * 1e4) / 1e4, py: Math.round(f.pivot.y * 1e4) / 1e4, ms: f.duration })),
  };
}
const body = `// GENERATED by scripts/gen-skill-fx.mjs from public/assets/vfx/*.json (frame rectangle, pivot inside the cell 0..1, duration in ms, in play order). Do not edit by hand.
export interface FxAtlasFrame {
  x: number;
  y: number;
  w: number;
  h: number;
  px: number;
  py: number;
  ms: number;
}
export interface FxAtlas {
  url: string;
  w: number; // sheet size in px (read from the PNG header)
  h: number;
  frames: FxAtlasFrame[];
}

export const FX_ATLAS: Record<string, FxAtlas> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync('src/game/skillFx.atlas.ts', body);
console.log('wrote', names.length, 'atlases');
