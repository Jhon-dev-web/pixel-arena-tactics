// Generates supabase/functions/_shared/materials/tables.ts: the game numbers the material server (material-claim / material-sync) judges a claim with. Run it with `npm run material:tables` and
// commit the result whenever a Hunting drop, a plant, an ore or wood tier or a gathering rate changes; materialServer.test.ts fails when the file is stale.
import { describe, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildMaterialTables } from './materialTablesBuild';

const OUT = resolve(__dirname, '../../supabase/functions/_shared/materials/tables.ts');

describe('material tables generator', () => {
  it('writes tables.ts', () => {
    const t = buildMaterialTables();
    const body = `// GENERATED by \`npm run material:tables\` (scripts/sim/materialTables.gen.ts) from the game's own code. Do not edit by hand.
// The server cannot import the game, so these are copies; src/game/__tests__/materialServer.test.ts fails when they go stale.

/** The materials that can have a tradeable variant: what a Hunting, Mining, Woodcutting or Garden claim produces. */
export const MATERIAL_IDS: readonly string[] = ${JSON.stringify(t.ids)};

/** How the game classes each material (a Hunting drop's own rarity, the tier of an ore or a wood, a plant's rarity): rates.ts gives each class its chance. */
export const MATERIAL_CLASS: Readonly<Record<string, 'common' | 'uncommon' | 'rare'>> = ${JSON.stringify(t.klass, null, 2)} as const;

/** Hunting: the most units an hour of each drop of each zone (the most economic rolls an hour x chance x best depth x best sub-level x Pass x Faro x Lure, with a small slack). */
export const HUNT_CEILING: Readonly<Record<string, Readonly<Record<string, number>>>> = ${JSON.stringify(t.hunt, null, 2)};

/** The ore tiers a Mining claim can be of, and the wood tiers of a Woodcutting claim. The most units an hour either can produce is MATERIAL_BOUNDS.gatherUnitsPerHour (materials/bounds.ts). */
export const MINING_TIERS: readonly string[] = ${JSON.stringify(t.mining)};
export const WOODCUTTING_TIERS: readonly string[] = ${JSON.stringify(t.woodcutting)};

/** Garden: each plant's base yield, its growth time and the most units an hour ONE plot of it can produce (fastest growth, rare-plant bonus, small slack). */
export const GARDEN_TABLE: Readonly<Record<string, { baseQty: number; durationMs: number; perPlotHour: number }>> = ${JSON.stringify(t.garden, null, 2)};

/** The plots of the Garden and how much faster than real time a harvest can come (both speed perks). */
export const GARDEN_PLOTS = ${t.plots};
export const GARDEN_SPEED_SLACK = ${t.gardenSpeedSlack};
`;
    writeFileSync(OUT, body);
  });
});
