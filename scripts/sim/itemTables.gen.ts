// Generates supabase/functions/_shared/items/tables.ts: the game numbers the item server (mint-item / bind-item) rolls and judges with. Run it with `npm run item:tables` and commit the
// result whenever the rarity table, the substat ranges, a recipe gate, a unique chance or the Gold Pouch denominations change; itemCertificates.test.ts fails when the file is stale.
import { describe, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildItemTables } from './itemTablesBuild';

const OUT = resolve(__dirname, '../../supabase/functions/_shared/items/tables.ts');

describe('item tables generator', () => {
  it('writes tables.ts', () => {
    const t = buildItemTables();
    const body = `// GENERATED by \`npm run item:tables\` (scripts/sim/itemTables.gen.ts) from the game's own code. Do not edit by hand.
// The server cannot import the game, so these are copies; src/game/__tests__/itemCertificates.test.ts fails when they go stale.

export type RarityId = 'common' | 'rare' | 'epic' | 'legendary';
export type SubstatKind = 'critRate' | 'critDamage' | 'lifesteal' | 'defense' | 'maxHp' | 'goldBonus';

/** The forge rarity table (rarity.ts RARITIES), in roll order. */
export const RARITY_TABLE: readonly { id: RarityId; chance: number; substatCount: number; substatMult: number }[] = ${JSON.stringify(t.rarities)};

/** The substat ranges (rarity.ts SUBSTATS): a roll is min + int(0..max-min) + round(perTier x tier), or, when \`ranges\` exists, the tier's own [min, max] in steps of 10^-decimals. */
export const SUBSTAT_TABLE: readonly { type: SubstatKind; min: number; max: number; perTier: number; ranges: readonly (readonly [number, number])[] | null; decimals: number }[] = ${JSON.stringify(t.substats)};

/** The Blacksmith's Seal (season reward): the forge roll is conditioned on this rarity or better, and the piece is born bound (gearInstances.applyForge). */
export const SEAL_MIN_RARITY: RarityId = ${JSON.stringify(t.sealMinRarity)};

/** The Legendary pity (rarity.ts FORGE_PITY): a normal forge of tier minTier or above that is not Legendary adds 1 to the account's counter; at threshold the next such forge is Legendary and the counter resets (roll.ts rollForgeRarity). */
export const PITY_TABLE = ${JSON.stringify(t.pity)} as const;

/** Seals the Pass track gives per season and the season length: the server lets a Pass owner use a few more than that (items/bounds.ts). */
export const SEAL_TABLE = ${JSON.stringify(t.seal)} as const;

/** Every forgeable instanced template (has a recipe, is not a unique): its tier, slot and the lowest hero level it can exist at (the recipe gate, inherited down the chain). */
export const FORGE_TEMPLATES: Readonly<Record<string, { tier: number; slot: string; levelGate: number }>> = ${JSON.stringify(t.forge, null, 2)};

/** Every unique (drop-only) template: its tier and slot. A unique rolls one extra substat slot. */
export const UNIQUE_TEMPLATES: Readonly<Record<string, { tier: number; slot: string }>> = ${JSON.stringify(t.unique, null, 2)};

/** Hunting hours of ONE forged piece of a tier through its whole recipe chain (npm run sim:cost model, scripts/sim/farmHours.ts: the hunting hours of the 7 pieces of a set through that tier, over 7). */
export const FARM_HOURS_PER_PIECE: Readonly<Record<number, number>> = ${JSON.stringify(t.farmHoursPerPiece)};

/** Hunting zones: the floor and the hero level (0 = none) that open each one, its storage cap, the economic rolls per hour its unique chances are sized for, and the uniques it drops (chance per economic roll). */
export const HUNT_ZONES: readonly { id: string; unlockFloor: number; unlockLevel: number; offlineCapHours: number; rollsPerHour: number; uniques: readonly { itemId: string; chance: number }[] }[] = ${JSON.stringify(t.zones)};

/** The most economic rolls per hour any build can reach (reference kills/h x roll cap, sub-level 1): the sized rolls above stay under it. */
export const MAX_ROLLS_PER_HOUR = ${t.maxRollsPerHour};

/** Dungeon bosses: which uniques each biome boss floor drops, the depth-boss pools and their chances (uniques.ts, dungeon.ts, tunables). */
export const BOSS_TABLE = ${JSON.stringify(t.boss, null, 2)} as const;

/** Sorte Grande: the multipliers a hero with the skill gets on the Hunting and boss unique chances (heroSkills.ts). The client claims it; the server allows at most these. */
export const LUCK_TABLE = ${JSON.stringify(t.luck)} as const;

/** The Gold Pouch (goldPouch.ts): the face values and how many a hero may create per day. */
export const POUCH_TABLE = ${JSON.stringify(t.pouch)} as const;

/** The Pass storage cap in hours (tunables battlePass.capHours): the longest a Hunting reward can wait to be claimed. */
export const PASS_CAP_HOURS = ${t.passCapHours};
`;
    writeFileSync(OUT, body);
  });
});
