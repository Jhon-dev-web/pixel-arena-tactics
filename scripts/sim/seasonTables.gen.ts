// Generates supabase/functions/_shared/progress/tables.ts: the few game numbers the server needs to judge a save (the hero XP curve, the level / floor gates of
// the gear and the zone unlock floors). The Edge Function runs in Deno and cannot import the game, so the numbers are copied here by this script. Run it with
// `npm run season:tables` and commit the result whenever xpCurve / paragon / gear gates change; seasonProgress.test.ts fails when the file is stale.
import { describe, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildTables } from './seasonTablesBuild';

const OUT = resolve(__dirname, '../../supabase/functions/_shared/progress/tables.ts');

describe('season tables generator', () => {
  it('writes tables.ts', () => {
    const t = buildTables();
    const body = `// GENERATED by \`npm run season:tables\` (scripts/sim/seasonTables.gen.ts) from the game's own code. Do not edit by hand.
// The server cannot import the game, so these are copies; src/game/__tests__/seasonProgress.test.ts fails when they go stale.

/** xpToLevel[l - 1] = the XP at which hero level l begins (level 1 = 0; level 100 = where the paragon starts). */
export const XP_TO_LEVEL: readonly number[] = ${JSON.stringify(t.xpToLevel)};

/** Paragon level n (n >= 1) costs Math.round(PARAGON_FIRST_XP * PARAGON_GROWTH ** (n - 1)) XP. */
export const PARAGON_FIRST_XP = ${t.paragonFirstXp};
export const PARAGON_GROWTH = ${t.paragonGrowth};

/** Lowest hero level at which a gear template can exist in a save (crafted: its recipe gate; unique: its twin's). */
export const GEAR_LEVEL_GATES: Readonly<Record<string, number>> = ${JSON.stringify(t.levelGates, null, 2)};

/** Lowest highestDungeonFloor at which a unique can exist (its biome boss floor, or the unlock floor of its hunting zone). */
export const UNIQUE_FLOOR_GATES: Readonly<Record<string, number>> = ${JSON.stringify(t.floorGates, null, 2)};

/** XP of one Dungeon run clearing floors 1..f (index f); index 100 includes 40 Profundezas depths. */
export const DUNGEON_RUN_XP: readonly number[] = ${JSON.stringify(t.dungeonRunXp)};

/** Hunting zones: the dungeon floor that opens each one and its XP per hour at the shallow depth. */
export const ZONE_TABLE: readonly { id: string; unlockFloor: number; xpPerHour: number }[] = ${JSON.stringify(t.zoneFloors)};
`;
    writeFileSync(OUT, body);
  });
});
