// Generates src/game/recommendedCp.ts, the "recommended CP" shown for every Dungeon floor. Run it with `npm run sim:cp` and commit the
// result. It MUST be re-run whenever the Dungeon curve changes (hpGrowth / dmgGrowth / waveHeal / boss multipliers / enemy bases...), which
// is why recommendedCp.test.ts also pins a few anchor floors.
//
// Method (all numbers come from the real game code through the sim driver, see ladder.ts):
//   1. A ladder of ~270 "reasonable builds": level 1..100 x (starter gear | tier 1..6 gear refined +0 / +4 / +8, only from the level that
//      lets the player craft that tier), attribute points spread like the sim player does. Plus the brand-new hero with unspent points.
//   2. For every floor, each build starts a Dungeon run on that floor at full HP, no potions, and the floor counts as won when it is
//      cleared. Combat is deterministic except for crits, so 3 seeded runs per build are enough.
//   3. Raw value of a floor = the lowest build CP such that at least 80% of the builds whose CP is within +10% above it win the floor.
//   4. Smoothing: the table is the running maximum of the raw values over the floors that are not mini-boss checkpoints (a checkpoint, floor
//      10/20/30..., is measured ~25% above its neighbours; it keeps its own value but does not raise the floors after it, otherwise they would
//      be overstated by up to 37%). So the table never decreases except right after a checkpoint. Rounded up.
import { afterAll, beforeAll, describe, it, vi } from 'vitest';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { computeCP, defaultSave } from '../../src/game/engine';
import { CP_WINDOW, ladder, recommendedTable, uncleared, WIN_SHARE } from './ladder';
import { gearOnly } from './duel';

const NOW = new Date(2026, 5, 20, 12, 0, 0).getTime();
const OUT = resolve(__dirname, '../../src/game/recommendedCp.ts');

describe('recommended CP table generator', () => {
  beforeAll(() => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(NOW);
  });
  afterAll(() => {
    vi.useRealTimers();
  });

  it('measures the ladder and writes src/game/recommendedCp.ts', () => {
    const builds = ladder();
    const { raw, table } = recommendedTable(builds, NOW);
    const capped = raw.map((v, i) => (Number.isFinite(v) ? 0 : i + 1)).filter(Boolean);
    const rows: string[] = [];
    for (let i = 0; i < table.length; i += 10) rows.push('  ' + table.slice(i, i + 10).join(', ') + ',');
    const text = [
      '// GENERATED by scripts/sim/cpTable.gen.ts (`npm run sim:cp`). Do not edit by hand: change the Dungeon tuning, then regenerate.',
      `// Method: ${builds.length} ladder builds (level 1-100 x gear tier 0-6 x refine +0/+4/+8, and +10/+12 for tier 5 and 6 from level 60); recommended CP of a floor = the lowest build CP from which`,
      `// at least ${WIN_SHARE * 100}% of the builds up to ${Math.round((CP_WINDOW - 1) * 100)}% stronger clear that floor starting at full HP with no potions; then a running maximum over the floors that are not mini-boss checkpoints (a checkpoint is a one-floor spike).`,
      `// Fresh hero CP: ${Math.round(computeCP(gearOnly(defaultSave())))}. Floors no ladder build clears (the value is what a power law over the measured floors asks of them, never less than the strongest build): ${capped.length ? capped.join(', ') : 'none'}.`,
      '// What it assumes: a hero that drinks no tonic and no potion and starts the floor at full HP (the sim player, who does both, clears the late floors with about a fifth less CP). Past the ladder the floors',
      '// are the power-law value; round17.test.ts checks them against level-100 heroes in tier 6 gear +8 to +12 (common to legendary, warrior skills, paragon 0-50): the hero whose CP is the one listed clears the floor.',
      '// REVIEW IN PHASE 8: this curve was generated by GEAR-ONLY heroes (an EMPTY rotation, scripts/sim/duel.ts gearOnly), but the real player has the equipment-ability rotation switched on (automatic by default, engine.ts effectiveRotation), so he is stronger than the curve assumes and the recommended CP is BELOW what he can take. It must be regenerated (npm run sim:cp) when the ability numbers are calibrated in phase 8.',
      '// Index 0 is floor 1.',
      'export const RECOMMENDED_CP_BY_FLOOR: readonly number[] = [',
      ...rows,
      '];',
      '',
    ].join('\n');
    writeFileSync(OUT, text);
    // Floors no build clears: report only (not tuned).
    const un = uncleared(builds, raw, NOW);
    const L: string[] = [];
    L.push('#### Andares que nenhum build da escada limpa, ou que só o build mais forte limpa (a tabela usa o CP do build mais forte)', '');
    L.push(`Ajuste: CP = exp(${un.fit.a.toFixed(3)}) x (HP x dano)^${un.fit.b.toFixed(3)}, sobre os andares >= 26 medidos.`, '');
    L.push('| Andar | HP x dano | Melhor build | CP dele | Vitórias dele (10 sorteios) | CP necessário (extrapolado) |', '| --: | --- | --- | --- | --- | --- |');
    for (const f of un.floors) L.push(`| ${f.floor} | ${f.power.toLocaleString('en-US').replace(/,/g, ' ')} | ${f.bestBuild} | ${Math.round(f.bestCp)} | ${f.bestWinRate}% | ${f.neededCp} |`);
    const top = builds[builds.length - 1].cp;
    const near = raw.map((v, i) => [i + 1, v] as const).filter(([, v]) => Number.isFinite(v) && v > 0.85 * top);
    L.push('', `Andares medidos mas a menos de 15% do topo da escada (CP ${Math.round(top)}): ${near.map(([f, v]) => `${f} (${v})`).join(', ') || 'nenhum'}`);
    // Smoothing check: how far above the measured value does the monotone table sit on floors 26-49?
    const over = table.map((v, i) => (Number.isFinite(raw[i]) ? v / raw[i] - 1 : 0));
    const worst = over.slice(25, 49).reduce((m, v, i) => (v > m.v ? { v, f: i + 26 } : m), { v: 0, f: 0 });
    L.push('', `Maior sobrestimativa da tabela nos andares 26-49: ${(worst.v * 100).toFixed(1)}% (andar ${worst.f}); acima de 10%: ${over.slice(25, 49).filter((v) => v > 0.1).length} andares`);
    console.log('\n' + L.join('\n') + '\n');
    console.log(`wrote ${OUT}\n` + [1, 3, 8, 10, 24, 25, 26, 50, 51, 75, 76, 100].map((f) => `floor ${f}: raw ${raw[f - 1]} -> ${table[f - 1]}`).join('\n'));
  });
});
