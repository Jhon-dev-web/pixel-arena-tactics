// Generates src/game/recommendedCp.ts, the "recommended CP" shown for every Dungeon floor. Run it with `npm run sim:cp` and commit the
// result. It MUST be re-run whenever the Dungeon curve changes (hpGrowth / dmgGrowth / waveHeal / boss multipliers / enemy bases...), which
// is why recommendedCp.test.ts also pins a few anchor floors.
//
// Method (all numbers come from the real game code through the sim driver, see ladder.ts):
//   1. A ladder of ~270 "reasonable builds": level 1..100 x (starter gear | tier 1..6 gear refined +0 / +4 / +8, only from the level that
//      lets the player craft that tier), attribute points spread like the sim player does. Plus the brand-new hero with unspent points.
//   2. For every floor, each build starts a Dungeon run on that floor at full HP, no potions, and the floor counts as won when it is
//      cleared. Combat is deterministic except for crits, so 3 seeded runs per build are enough.
//   3. Raw value of a floor = the lowest build CP such that at least 80% of the builds whose CP is within +10% above it win the floor.
//   4. Smoothing: the table is the running maximum of the raw values (never decreases from one floor to the next), rounded up.
import { afterAll, beforeAll, describe, it, vi } from 'vitest';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { computeCP, defaultSave } from '../../src/game/engine';
import { CP_WINDOW, ladder, recommendedTable, WIN_SHARE } from './ladder';

const NOW = new Date(2026, 5, 20, 12, 0, 0).getTime();
const OUT = resolve(__dirname, '../../src/game/recommendedCp.ts');

describe('recommended CP table generator', () => {
  beforeAll(() => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(NOW);
  });
  afterAll(() => {
    vi.useRealTimers();
  });

  it('measures the ladder and writes src/game/recommendedCp.ts', () => {
    const builds = ladder();
    const { raw, table } = recommendedTable(builds, NOW);
    const capped = raw.map((v, i) => (Number.isFinite(v) ? 0 : i + 1)).filter(Boolean);
    const rows: string[] = [];
    for (let i = 0; i < table.length; i += 10) rows.push('  ' + table.slice(i, i + 10).join(', ') + ',');
    const text = [
      '// GENERATED by scripts/sim/cpTable.gen.ts (`npm run sim:cp`). Do not edit by hand: change the Dungeon tuning, then regenerate.',
      `// Method: ${builds.length} ladder builds (level 1-100 x gear tier 0-6 x refine +0/+4/+8); recommended CP of a floor = the lowest build CP from which`,
      `// at least ${WIN_SHARE * 100}% of the builds up to ${Math.round((CP_WINDOW - 1) * 100)}% stronger clear that floor starting at full HP with no potions; then the running maximum over floors.`,
      `// Fresh hero CP: ${Math.round(computeCP(defaultSave()))}. Floors no ladder build clears (value = CP of the strongest build): ${capped.length ? capped.join(', ') : 'none'}.`,
      '// Index 0 is floor 1.',
      'export const RECOMMENDED_CP_BY_FLOOR: readonly number[] = [',
      ...rows,
      '];',
      '',
    ].join('\n');
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}\n` + [1, 3, 8, 10, 24, 25, 26, 50, 51, 75, 76, 100].map((f) => `floor ${f}: raw ${raw[f - 1]} -> ${table[f - 1]}`).join('\n'));
  });
});
