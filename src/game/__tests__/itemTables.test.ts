import { describe, expect, it } from 'vitest';
import { GEAR } from '../gear';
import { HUNTING_ZONES } from '../huntingZones';
import { RARITIES, rollRarity, rollRarityAtLeast, rollSubstats } from '../rarity';
import { rollBossUniques, rollDepthBossUniques, rollUniqueDrop } from '../uniques';
import { buildItemTables } from '../../../scripts/sim/itemTablesBuild';
import { ITEM_BOUNDS, MARGIN } from '../../../supabase/functions/_shared/items/bounds';
import * as server from '../../../supabase/functions/_shared/items/roll';
import * as tables from '../../../supabase/functions/_shared/items/tables';
import { PACE_REJECT_FACTOR } from '../../../supabase/functions/_shared/progress/bounds';

// The item server copies a few game numbers (items/tables.ts, generated by `npm run item:tables`) and re-implements the dice over them. These tests fail the day the game moves and the
// copies do not, and prove that the server rolls the SAME outcome the game would from the same random stream.

function lcg(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

describe('items/tables.ts is exactly what `npm run item:tables` would write now', () => {
  const t = buildItemTables();
  it('rarities, substats, templates, zones, bosses, luck, pouches, seals', () => {
    expect([...tables.RARITY_TABLE]).toEqual(t.rarities);
    expect(JSON.parse(JSON.stringify(tables.SUBSTAT_TABLE))).toEqual(t.substats);
    expect(tables.SEAL_MIN_RARITY).toBe(t.sealMinRarity);
    expect(tables.PITY_TABLE).toEqual(t.pity);
    expect(tables.FORGE_TEMPLATES).toEqual(t.forge);
    expect(tables.UNIQUE_TEMPLATES).toEqual(t.unique);
    expect(tables.FARM_HOURS_PER_PIECE).toEqual(t.farmHoursPerPiece);
    expect(JSON.parse(JSON.stringify(tables.HUNT_ZONES))).toEqual(t.zones);
    expect(tables.MAX_ROLLS_PER_HOUR).toBe(t.maxRollsPerHour);
    expect(JSON.parse(JSON.stringify(tables.BOSS_TABLE))).toEqual(JSON.parse(JSON.stringify(t.boss)));
    expect(tables.LUCK_TABLE).toEqual(t.luck);
    expect(JSON.parse(JSON.stringify(tables.POUCH_TABLE))).toEqual(JSON.parse(JSON.stringify(t.pouch)));
    expect(JSON.parse(JSON.stringify(tables.SEAL_TABLE))).toEqual(t.seal);
    expect(tables.PASS_CAP_HOURS).toBe(t.passCapHours);
  });

  it('every forgeable piece and every unique is in the right table, and nothing else is', () => {
    const forgeable = GEAR.filter((g) => g.slot !== 'relic' && !g.unique && g.recipe).map((g) => g.id);
    const uniques = GEAR.filter((g) => g.slot !== 'relic' && g.unique).map((g) => g.id);
    expect(Object.keys(tables.FORGE_TEMPLATES).sort()).toEqual(forgeable.sort());
    expect(Object.keys(tables.UNIQUE_TEMPLATES).sort()).toEqual(uniques.sort());
  });

  it('every unique drops from exactly one place the server knows', () => {
    const sources: Record<string, number> = {};
    for (const z of tables.HUNT_ZONES) for (const u of z.uniques) sources[u.itemId] = (sources[u.itemId] ?? 0) + 1;
    for (const ids of Object.values(tables.BOSS_TABLE.biomePools)) for (const id of ids) sources[id] = (sources[id] ?? 0) + 1;
    expect(Object.keys(sources).sort()).toEqual(Object.keys(tables.UNIQUE_TEMPLATES).sort());
    for (const n of Object.values(sources)) expect(n).toBe(1);
  });

  it('the rolls per hour the unique chances are sized for stay under the most any build can reach', () => {
    for (const z of tables.HUNT_ZONES) {
      expect(z.rollsPerHour, z.id).toBeGreaterThan(0);
      expect(z.rollsPerHour, z.id).toBeLessThanOrEqual(tables.MAX_ROLLS_PER_HOUR);
      expect(z.unlockFloor).toBe(HUNTING_ZONES.find((g) => g.id === z.id)?.unlockFloor);
    }
  });
});

describe('the server rolls what the game would roll from the same random stream', () => {
  it('rollRarity', () => {
    for (let seed = 1; seed <= 400; seed++) expect(server.rollRarity(lcg(seed))).toBe(rollRarity(lcg(seed)));
    // the table itself: 61 / 25 / 10 / 4 (Rodada 26)
    expect(RARITIES.map((r) => r.chance)).toEqual([0.61, 0.25, 0.1, 0.04]);
    expect(tables.RARITY_TABLE.map((r) => r.chance)).toEqual([0.61, 0.25, 0.1, 0.04]);
  });

  it('rollRarityAtLeast (the Blacksmith\'s Seal)', () => {
    for (let seed = 1; seed <= 400; seed++) expect(server.sealRarity(lcg(seed))).toBe(rollRarityAtLeast('epic', lcg(seed)));
    const counts = { epic: 0, legendary: 0 } as Record<string, number>;
    const rng = lcg(99);
    for (let i = 0; i < 6000; i++) counts[server.sealRarity(rng)]++;
    expect(counts.legendary / 6000).toBeGreaterThan(0.25);
    expect(counts.legendary / 6000).toBeLessThan(0.32); // 4 / 14 = 28.6 %
  });

  it('rollSubstats for every rarity, tier and extra slot', () => {
    for (const rarity of ['common', 'rare', 'epic', 'legendary'] as const) {
      for (let tier = 1; tier <= 6; tier++) {
        for (const extra of [0, 1]) {
          for (let seed = 1; seed <= 25; seed++) expect(server.rollSubstats(rarity, tier, extra, lcg(seed))).toEqual(rollSubstats(rarity, tier, extra, lcg(seed)));
        }
      }
    }
  });

  it('rollUnique equals rollUniqueDrop for every unique', () => {
    for (const id of Object.keys(tables.UNIQUE_TEMPLATES)) {
      for (let seed = 1; seed <= 40; seed++) {
        const mine = server.rollUnique(id, tables.UNIQUE_TEMPLATES[id].tier, lcg(seed));
        expect(mine).toEqual(rollUniqueDrop(id, lcg(seed)));
      }
    }
  });

  it('the boss uniques equal the game\'s for biome and depth bosses, with and without luck', () => {
    const tierOf = (id: string) => tables.UNIQUE_TEMPLATES[id]?.tier ?? 0;
    const biome = [25, 50, 75, 100];
    for (const luck of [1, 1.25]) {
      for (let seed = 1; seed <= 300; seed++) {
        // the game rolls ONE stage at a time with a luck factor; the server rolls a list: chain the same stream
        const g = lcg(seed);
        const expected = biome.flatMap((stage) => rollBossUniques(stage, g, luck));
        expect(server.rollBossUniques(biome, luck, tierOf, lcg(seed))).toEqual(expected);
        const d = lcg(seed + 1000);
        const depths = [10, 20, 30, 40, 50];
        const expectedDepth = depths.flatMap((depth) => rollDepthBossUniques(depth, d, luck));
        expect(server.rollBossUniques(depths.map((x) => 100 + x), luck, tierOf, lcg(seed + 1000))).toEqual(expectedDepth);
      }
    }
  });

  it('isBossStage matches the dungeon: the four biome bosses and every tenth depth', () => {
    const ok = [25, 50, 75, 100, 110, 120, 200];
    const bad = [0, 1, 24, 26, 99, 101, 105, 111, -25, 25.5];
    for (const s of ok) expect(server.isBossStage(s), String(s)).toBe(true);
    for (const s of bad) expect(server.isBossStage(s), String(s)).toBe(false);
  });
});

describe('the limits table', () => {
  it('forge rates follow the hunting hours of one piece with the margin, and the daily caps are never under the floor', () => {
    for (let tier = 1; tier <= 6; tier++) {
      const hours = Math.max(0.5, tables.FARM_HOURS_PER_PIECE[tier]);
      expect(ITEM_BOUNDS.forgeRatePerHour(tier)).toBeCloseTo(MARGIN / hours, 9);
      expect(ITEM_BOUNDS.forgeCapacity(tier)).toBeGreaterThanOrEqual(2);
      expect(ITEM_BOUNDS.certDayCap(tier)).toBeGreaterThanOrEqual(4);
    }
    // the dearer the tier the fewer pieces a day
    for (let tier = 2; tier <= 5; tier++) expect(ITEM_BOUNDS.forgeRatePerHour(tier)).toBeLessThanOrEqual(ITEM_BOUNDS.forgeRatePerHour(tier - 1));
  });

  it('the Gold pouch bucket holds the biggest pouch and a day of income is less than the biggest pouch', () => {
    expect(ITEM_BOUNDS.pouchGoldCapacity()).toBe(Math.max(...Object.values(tables.POUCH_TABLE.faces)));
    expect(ITEM_BOUNDS.pouchGoldPerDay).toBeLessThanOrEqual(ITEM_BOUNDS.pouchGoldCapacity());
  });

  it('the Seal limit is the margin over what the track gives', () => {
    expect(tables.SEAL_TABLE.perSeason).toBe(3);
    expect(ITEM_BOUNDS.sealCapacity).toBe(MARGIN * 3);
    expect(ITEM_BOUNDS.sealRatePerHour * tables.SEAL_TABLE.seasonDays * 24).toBeCloseTo(ITEM_BOUNDS.sealCapacity, 9);
  });

  it('the hunting time bucket is the Pass storage cap', () => {
    expect(ITEM_BOUNDS.huntCapacitySeconds).toBe(tables.PASS_CAP_HOURS * 3600);
  });

  it('reuses the ranking\'s pace factor for the account-age gates', () => {
    expect(PACE_REJECT_FACTOR).toBe(3);
  });
});

describe('the zones keep the unique chances of the game', () => {
  it('each zone\'s uniques and chances are the game\'s', () => {
    for (const z of HUNTING_ZONES) {
      const s = tables.HUNT_ZONES.find((x) => x.id === z.id)!;
      expect(s.uniques.map((u) => [u.itemId, u.chance])).toEqual((z.uniques ?? []).map((u) => [u.itemId, u.chance]));
    }
  });
});
