import { describe, expect, it } from 'vitest';
import { hero } from '../../../scripts/sim/duel';
import { buildMaterialTables } from '../../../scripts/sim/materialTablesBuild';
import { buildHuntSession, computeHuntingStatus, computeMiningStatus, computeWoodcuttingStatus, defaultSave, SaveData } from '../engine';
import { HUNTING_ZONES, HuntingDepth } from '../huntingZones';
import { PLANTS } from '../garden';
import { skillXpToReachLevel } from '../skills';
import { TRADEABLE_MATERIALS } from '../tradeableMaterials';
import T from '../tunables';
import { MATERIAL_BOUNDS } from '../../../supabase/functions/_shared/materials/bounds';
import { HONEST_PEAK_DAY_UNITS } from '../../../supabase/functions/_shared/materials/rates';
import * as tables from '../../../supabase/functions/_shared/materials/tables';

// The material server copies a few game numbers (materials/tables.ts, generated by `npm run material:tables`). These tests fail the day the game moves and the copy does not, and prove that the
// plausibility ceilings the server judges a claim with stay at or above what the game can really produce.

const HOUR = 3600 * 1000;
const START = 1_800_000_000_000;

describe('materials/tables.ts is exactly what `npm run material:tables` would write now', () => {
  const t = buildMaterialTables();
  it('ids, classes, ceilings, tiers, plants and plots', () => {
    expect([...tables.MATERIAL_IDS]).toEqual(t.ids);
    expect(tables.MATERIAL_CLASS).toEqual(t.klass);
    expect(JSON.parse(JSON.stringify(tables.HUNT_CEILING))).toEqual(JSON.parse(JSON.stringify(t.hunt)));
    expect([...tables.MINING_TIERS]).toEqual(t.mining);
    expect([...tables.WOODCUTTING_TIERS]).toEqual(t.woodcutting);
    expect(JSON.parse(JSON.stringify(tables.GARDEN_TABLE))).toEqual(JSON.parse(JSON.stringify(t.garden)));
    expect(tables.GARDEN_PLOTS).toBe(t.plots);
    expect(tables.GARDEN_SPEED_SLACK).toBe(t.gardenSpeedSlack);
  });

  it('the materials that can be tradeable are exactly what the game lists, and every one has a daily peak', () => {
    expect([...tables.MATERIAL_IDS].sort()).toEqual([...TRADEABLE_MATERIALS].sort());
    expect(Object.keys(HONEST_PEAK_DAY_UNITS).sort()).toEqual([...TRADEABLE_MATERIALS].sort());
  });
});

describe('the ceilings are never under what the game can produce', () => {
  // A hero at the max sub-level of every depth (no promotion can happen, so a real session stays on the level the estimate pins), like huntEstimate.test.ts.
  const maxed = (s: SaveData): SaveData => {
    const huntProgress: SaveData['huntProgress'] = {};
    for (const z of HUNTING_ZONES) for (const d of ['shallow', 'dense', 'deep'] as HuntingDepth[]) huntProgress[`${z.id}:${d}`] = { ceiling: T.hunting.subLevels, promotionWins: 0 };
    return { ...s, huntProgress, consumables: { ...s.consumables, small_hp: 0, large_hp: 0, greater_elixir: 0 } };
  };
  const realHour = (s: SaveData, zoneId: string, depth: HuntingDepth) => {
    const hunting: SaveData = { ...s, activeHuntingZone: zoneId, activeHuntingDepth: depth, huntingOfflineStart: START, huntSession: buildHuntSession(s, START) };
    return computeHuntingStatus(hunting, START + HOUR);
  };

  it.each([
    ['tier 1 hero, Demon Glade, shallow', () => maxed({ ...hero('1', 4, { level: 14 }), highestDungeonFloor: 90 }), 'demon_glade', 'shallow' as HuntingDepth],
    ['tier 3 hero, Blood Marsh, dense', () => maxed({ ...hero('3', 6, { level: 35 }), highestDungeonFloor: 90 }), 'blood_marsh', 'dense' as HuntingDepth],
    ['tier 5 hero, Blood Abyss, deep', () => maxed({ ...hero('5', 10, { level: 75 }), highestDungeonFloor: 90 }), 'blood_abyss', 'deep' as HuntingDepth],
  ])('Hunting (%s): one real hour never yields more of a drop than its ceiling an hour', (_name, make, zone, depth) => {
    const drops = realHour(make(), zone, depth).drops as Record<string, number>;
    for (const [id, n] of Object.entries(drops)) {
      expect(tables.HUNT_CEILING[zone][id], `${zone}/${id}`).toBeDefined();
      expect(n, `${zone}/${id}`).toBeLessThanOrEqual(Math.ceil(tables.HUNT_CEILING[zone][id]));
    }
  });

  it('Mining and Woodcutting: the best build (profession cap, the Pass, every bonus) stays under the units an hour', () => {
    for (const [kind, tier] of [['mining', 'obsidian'], ['woodcutting', 'ancient_wood']] as const) {
      const base = defaultSave();
      const skillXp = { ...base.skillXp, [kind]: skillXpToReachLevel(75, kind) };
      const s: SaveData = {
        ...base,
        skillXp,
        hasBattlePass: true,
        ...(kind === 'mining' ? { activeOreId: tier, lastMiningClaim: START, miningCapHours: 10, miningPass: { active: true, capHours: 10 } } : { activeWoodId: tier, lastWoodcuttingClaim: START, woodcuttingCapHours: 10, woodcuttingPass: { active: true, capHours: 10 } }),
      };
      const st = kind === 'mining' ? computeMiningStatus(s, START + HOUR) : computeWoodcuttingStatus(s, START + HOUR);
      const units = kind === 'mining' ? (st as { oreReady: number }).oreReady : (st as { woodReady: number }).woodReady;
      expect(units).toBeGreaterThan(30);
      expect(units, kind).toBeLessThanOrEqual(MATERIAL_BOUNDS.gatherUnitsPerHour);
    }
  });

  it('Garden: one plot of a plant never yields more an hour than its table says (both speed perks and the rare bonus included)', () => {
    for (const p of PLANTS) {
      const perHour = (p.qty + (p.rarity === 'rare' ? T.mastery.gardenRareBonus : 0)) / ((p.durationMs / HOUR) * (1 - 2 * T.mastery.gardenSpeedPct));
      expect(tables.GARDEN_TABLE[p.material].perPlotHour, p.id).toBeGreaterThanOrEqual(perHour);
    }
  });

  it('a day of the honest fast players\' sim is within what the ceilings allow in 24 hours (so an honest claim is never cut)', () => {
    for (const id of TRADEABLE_MATERIALS) {
      const peak = HONEST_PEAK_DAY_UNITS[id];
      const hunt = Math.max(0, ...Object.values(tables.HUNT_CEILING).map((z) => z[id] ?? 0)) * 24;
      const gather = tables.MINING_TIERS.includes(id) || tables.WOODCUTTING_TIERS.includes(id) ? MATERIAL_BOUNDS.gatherUnitsPerHour * 24 : 0;
      const garden = (tables.GARDEN_TABLE[id]?.perPlotHour ?? 0) * tables.GARDEN_PLOTS * 24;
      expect(Math.max(hunt, gather, garden), id).toBeGreaterThanOrEqual(peak);
    }
  });
});
