export const MARKET_TEXT = { pt, en } as const;

function read(tree: Tree, path: string): string | undefined {
  let node: string | Tree | undefined = tree;
  for (const key of path.split('.')) {
    if (!node || typeof node === 'string') return undefined;
    node = node[key];
  }
  return typeof node === 'string' ? node : undefined;
}

/** The market's text in the active language (falls back to Portuguese, then to the key itself so a gap is visible, never blank). */
export function mt(path: string, vars?: Record<string, string | number>): string {
  const raw = read(MARKET_TEXT[activeLocale === 'en' ? 'en' : 'pt'], path) ?? read(pt, path) ?? path;
  return vars ? raw.replace(/\{(\w+)\}/g, (whole, k) => String(vars[k] ?? whole)) : raw;
}
